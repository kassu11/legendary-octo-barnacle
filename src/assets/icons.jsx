import { Show, splitProps } from "solid-js";

/*
 * All application icons.
 *
 * Every icon forwards its props to the root <svg>, so custom attributes (class, style, scoped, data-*, event handlers, ...)
 * can be passed directly to the icon. Passed props override the icon defaults.
 *
 * Icons are decorative by default (aria-hidden="true").
 * Passing a `title`, `aria-label` or `aria-labelledby` makes the icon an accessible image (role="img") instead.
 */
function Svg(props) {
  const [local, attributes] = splitProps(props, ["title", "children"]);
  const labelled = () => Boolean(local.title || attributes["aria-label"] || attributes["aria-labelledby"]);

  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      focusable="false"
      aria-hidden={labelled() ? undefined : "true"}
      role={labelled() ? "img" : undefined}
      {...attributes}
    >
      <Show when={local.title}>
        <title>{local.title}</title>
      </Show>
      {local.children}
    </svg>
  );
}

